#!/usr/bin/env node
/**
 * Builds one word list for import-vocabulary.mjs from Goethe-Institut word lists
 * (CSV or TSV whose first column is the headword, e.g. "die Adresse,-en",
 * "abbiegen, biegt ab, bog ab, ist abgebogen", "abholen(1)", "ab").
 *
 * Every headword is written once with the LOWEST level it appears in, because the
 * official lists are cumulative (the B1 list contains the A1 and A2 words too).
 * Only headwords are used, which words exist at which level. Example sentences,
 * translations and audio from such lists are copyrighted and are never copied.
 *
 *   node scripts/import/goethe-to-wordlist.mjs --out list.txt --in a1/*.tsv A1 --in a2/*.tsv A2 --in b1.csv B1
 *   (each --in takes one or more files followed by the level)
 */
import { readFileSync, writeFileSync } from 'node:fs';

const LEVELS = ['A1', 'A2', 'B1'];
const inputs = [];
let out = null;
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--out') out = argv[++i];
  else if (argv[i] === '--in') {
    const files = [];
    while (argv[i + 1] && !LEVELS.includes(argv[i + 1]) && !argv[i + 1].startsWith('--')) files.push(argv[++i]);
    const level = argv[++i];
    if (!LEVELS.includes(level) || files.length === 0) throw new Error('--in needs files followed by a level (A1, A2 or B1)');
    inputs.push({ files, level });
  }
}
if (!out || inputs.length === 0) {
  console.error('usage: goethe-to-wordlist.mjs --out <list.txt> --in <files...> <LEVEL> [--in ...]');
  process.exit(1);
}

/** Minimal CSV parser (quoted fields may contain commas and newlines). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (c !== '\r') field += c;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function firstColumn(file) {
  const text = readFileSync(file, 'utf8');
  const rows = file.endsWith('.tsv') ? text.split('\n').map((line) => line.split('\t')) : parseCsv(text);
  return rows.map((r) => (r[0] ?? '').trim()).filter((w) => w && !/^(word|german word)$/i.test(w));
}

/** "die Adresse,-en" -> "Adresse"; "abholen(1)" -> "abholen"; "(sich) ärgern" -> "ärgern"; "all-" -> "all". */
function headword(raw) {
  let w = raw.split(',')[0].trim();
  w = w.replace(/\(.*?\)/g, ' ').replace(/\s+/g, ' ').trim();
  w = w.replace(/^(der|die|das)\s+/i, '').replace(/^sich\s+/, '');
  w = w.split('/')[0].trim();
  w = w.replace(/[.…!?:]+$/, '').replace(/^-|-$/g, '').trim();
  if (!w || /\s/.test(w) || /\d/.test(w) || w.length < 2) return null;
  return w;
}

const levelOf = new Map();
const perLevel = { A1: 0, A2: 0, B1: 0 };
let skipped = 0;
for (const { files, level } of inputs.sort((a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level))) {
  for (const file of files) {
    for (const raw of firstColumn(file)) {
      const title = headword(raw);
      if (!title) {
        skipped++;
        continue;
      }
      if (!levelOf.has(title)) {
        levelOf.set(title, level);
        perLevel[level]++;
      }
    }
  }
}
const lines = [...levelOf.entries()].map(([title, level]) => `${title} ${level}`);
writeFileSync(out, `# Generated by goethe-to-wordlist.mjs: headwords only, lowest level wins.\n${lines.join('\n')}\n`);
console.log(`${lines.length} headwords written to ${out}:`, perLevel, `(${skipped} multi-word or empty entries skipped)`);
